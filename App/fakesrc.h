/*********************************************************************
* 文件：fakesrc.h
* 说明：A 板数据源模拟器 —— 在 B 板上生成符合协议 V1.1 的 260 字节
*       数据帧，用于在 A 板未联调前独立验证「接收→CRC→解析→显示」。
*
*       信号按「绝对时间」生成，因此切换时基后波形密度会真实变化，
*       而测量出的频率保持不变（与真实采集端行为一致）。
*********************************************************************/
#ifndef FAKESRC_H
#define FAKESRC_H

#include <stdint.h>

/* 待模拟的信号频率（Hz）
   选值原则：让「1ms/格」（窗口 10ms）能看到 2.5~10 个完整周期，
   这样才能验证任务书要求的「1ms 档分辨 0.1ms 跳变」。
   10ms/格（窗口 100ms）下会显得较密，这是示波器看高频信号的正常表现。 */
#define FAKE_FREQ_CH1     250     /* 模拟通道 1：正弦 */
#define FAKE_FREQ_CH2     1000    /* 模拟通道 2：三角波（对应麦克风音频频段） */
#define FAKE_FREQ_D1      1000    /* 数字通道 1：周期 1ms，脉宽 0.5ms */
#define FAKE_FREQ_D2      500     /* 数字通道 2：周期 2ms，脉宽 1ms */
#define FAKE_FREQ_D3      250     /* 数字通道 3：周期 4ms，脉宽 2ms */

void fakesrc_init(void);

/* 生成一帧 260 字节数据帧
   gear     : 当前时基档位 0..4（决定单点采样间隔）
   ch_mask  : 当前通道掩码，关闭的通道按协议填 0
   返回该帧 SEQ */
uint16_t fakesrc_tick(uint8_t *out, uint8_t gear, uint8_t ch_mask);

#endif /* FAKESRC_H */