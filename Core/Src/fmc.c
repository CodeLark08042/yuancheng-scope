SDRAM_HandleTypeDef hsdram1;

/* FMC initialization function */
void MX_FMC_Init(void)
{
  /* USER CODE BEGIN FMC_Init 0 */

  /* USER CODE END FMC_Init 0 */

  FMC_SDRAM_TimingTypeDef SdramTiming = {0};

  /* USER CODE BEGIN FMC_Init 1 */

  /* USER CODE END FMC_Init 1 */

  /** Perform the SDRAM1 memory initialization sequence
  */
  hsdram1.Instance = FMC_SDRAM_DEVICE;
  /* hsdram1.Init */
  hsdram1.Init.SDBank = FMC_SDRAM_BANK1;
  hsdram1.Init.ColumnBitsNumber = FMC_SDRAM_COLUMN_BITS_NUM_8;
  hsdram1.Init.RowBitsNumber = FMC_SDRAM_ROW_BITS_NUM_12;
  hsdram1.Init.MemoryDataWidth = FMC_SDRAM_MEM_BUS_WIDTH_16;
  hsdram1.Init.InternalBankNumber = FMC_SDRAM_INTERN_BANKS_NUM_4;
  hsdram1.Init.CASLatency = FMC_SDRAM_CAS_LATENCY_2;
  hsdram1.Init.WriteProtection = FMC_SDRAM_WRITE_PROTECTION_DISABLE;
  hsdram1.Init.SDClockPeriod = FMC_SDRAM_CLOCK_PERIOD_3;   /* SDCLK = HCLK/3 = 72MHz。
      ST BSP 仅在 HCLK=200MHz(SDCLK=100MHz) 下验证过；本工程 HCLK=216MHz，
      用 /2 会得到 108MHz，超出 MT48LC4M32B2 在 CL2 下的 100MHz 上限，导致读写失败。 */
  hsdram1.Init.ReadBurst = FMC_SDRAM_RBURST_ENABLE;
  hsdram1.Init.ReadPipeDelay = FMC_SDRAM_RPIPE_DELAY_0;
  /* SdramTiming */
  SdramTiming.LoadToActiveDelay = 2;
  SdramTiming.ExitSelfRefreshDelay = 7;
  SdramTiming.SelfRefreshTime = 4;
  SdramTiming.RowCycleDelay = 7;
  SdramTiming.WriteRecoveryTime = 2;
  SdramTiming.RPDelay = 2;
  SdramTiming.RCDDelay = 2;

  if (HAL_SDRAM_Init(&hsdram1, &SdramTiming) != HAL_OK)
  {
    Error_Handler( );
  }

  /* USER CODE BEGIN FMC_Init 2 */
  FMC_SDRAM_CommandTypeDef Command;

  /* 命令超时统一用 0xFFFF（与 ST BSP 的 SDRAM_TIMEOUT 一致）。
     0x1000 在 216MHz 下只够轮询约 90us，而 8 次自动刷新需要约 125us，
     会提前超时返回，导致后续 LOAD_MODE 在刷新期间被丢弃、模式寄存器未写入。 */
  /* 1. SDRAM Clock Enable，等待芯片稳定 */
  Command.CommandMode            = FMC_SDRAM_CMD_CLK_ENABLE;
  Command.CommandTarget          = FMC_SDRAM_CMD_TARGET_BANK1;
  Command.AutoRefreshNumber      = 1;
  Command.ModeRegisterDefinition = 0;
  HAL_SDRAM_SendCommand(&hsdram1, &Command, 0xFFFF);
  HAL_Delay(1);

  /* 2. Precharge All（全预充电） */
  Command.CommandMode            = FMC_SDRAM_CMD_PALL;
  Command.CommandTarget          = FMC_SDRAM_CMD_TARGET_BANK1;
  Command.AutoRefreshNumber      = 1;
  Command.ModeRegisterDefinition = 0;
  HAL_SDRAM_SendCommand(&hsdram1, &Command, 0xFFFF);

  /* 3. Auto Refresh：上电后需连续多次刷新才能进入稳定状态，BSP 用 8 次 */
  Command.CommandMode            = FMC_SDRAM_CMD_AUTOREFRESH_MODE;
  Command.CommandTarget          = FMC_SDRAM_CMD_TARGET_BANK1;
  Command.AutoRefreshNumber      = 8;
  Command.ModeRegisterDefinition = 0;
  HAL_SDRAM_SendCommand(&hsdram1, &Command, 0xFFFF);
  HAL_Delay(1);   /* 确保 8 次刷新全部完成后再写模式寄存器 */

  /* 4. Load Mode Register：BL=1、顺序突发、CAS=2、单次写突发
        0x0220 = WRITEBURST_MODE_SINGLE(0x200) | CAS_LATENCY_2(0x020)
        注意：必须与 Init.CASLatency = CAS_LATENCY_2 保持一致。 */
  Command.CommandMode            = FMC_SDRAM_CMD_LOAD_MODE;
  Command.CommandTarget          = FMC_SDRAM_CMD_TARGET_BANK1;
  Command.AutoRefreshNumber      = 1;
  Command.ModeRegisterDefinition = 0x0220;
  HAL_SDRAM_SendCommand(&hsdram1, &Command, 0xFFFF);

  /* 5. 设置刷新率：COUNT = 64ms/4096行 × 72MHz - 20 ≈ 1105 = 0x0451
        （刷新计数必须随 SDCLK 变化，原 0x0603 是按 100MHz 算的，在 72MHz 下刷新过慢会丢数据） */
  HAL_SDRAM_ProgramRefreshRate(&hsdram1, 0x0451);

  /* USER CODE END FMC_Init 2 */
}

